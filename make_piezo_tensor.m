function A = make_piezo_tensor(material)
% make_piezo_tensor: Create piezoelectric-type tensor A (3×3×3) for 8 materials
% Piezoelectric tensor symmetry: a_{ijk} = a_{ikj} (symmetric in last two indices)
% Data source: Chen, Jakli, Qi, "Spectral analysis of piezoelectric tensors",
% J. Phys. A 51 (2017) 025206 (ref [12] in S-type inclusion paper).
% Listed entries are expanded to the full tensor using a_{ijk}=a_{ikj}.

    A = zeros(3, 3, 3);

    switch lower(material)
        case 'vfesb'  % 43m crystal system
            % a123 = a213 = a312 = 3.68180667 (paper uses + sign;
            % sign flip only negates all eigenvalues, |lambda_max| unchanged)
            a123 = 3.68180667;
            A(1,2,3) = a123; A(1,3,2) = a123;
            A(2,1,3) = a123; A(2,3,1) = a123;
            A(3,1,2) = a123; A(3,2,1) = a123;

        case 'sio2'  % alpha-quartz, crystal system 32
            % a111 = -a122 = -a212 = -0.13685, a123 = -a213 = -0.009715
            a111 = -0.13685;
            a122 =  0.13685;
            a123 = -0.009715;
            a213 =  0.009715;
            A(1,1,1) = a111;
            A(1,2,2) = a122;
            A(1,2,3) = a123; A(1,3,2) = a123;
            A(2,1,2) = a122; A(2,2,1) = a122;
            A(2,1,3) = a213; A(2,3,1) = a213;

        case 'cr2agbio8'
            % a123 = a213 = -0.22163, a113 = -a223 = 2.608665,
            % a311 = -a322 = 0.152485, a312 = -0.37153
            a123 = -0.22163;
            a113 =  2.608665;
            a223 = -2.608665;
            a311 =  0.152485;
            a322 = -0.152485;
            a312 = -0.37153;
            A(1,2,3) = a123; A(1,3,2) = a123;
            A(2,1,3) = a123; A(2,3,1) = a123;
            A(1,1,3) = a113; A(1,3,1) = a113;
            A(2,2,3) = a223; A(2,3,2) = a223;
            A(3,1,1) = a311;
            A(3,2,2) = a322;
            A(3,1,2) = a312; A(3,2,1) = a312;

        case 'rbtao3'  % 3m crystal system
            % a113=a223=-8.40955, a222=-a212=-a211=-5.412525,
            % a311=a322=-4.3031, a333=-5.14766
            a113 = -8.40955; a222 = -5.412525;
            a311 = -4.3031;  a333 = -5.14766;
            A(1,1,3) = a113; A(1,3,1) = a113;
            A(2,2,2) = a222;
            A(2,1,1) = -a222; A(2,1,2) = -a222; A(2,2,1) = -a222;
            A(2,2,3) = a113; A(2,3,2) = a113;
            A(3,1,1) = a311; A(3,2,2) = a311;
            A(3,3,3) = a333;

        case 'nabis2'  % mm2 crystal system
            % a113=-8.90808, a223=-0.00842, a311=-7.11526,
            % a322=-0.6222, a333=-7.93831
            a113 = -8.90808; a223 = -0.00842;
            a311 = -7.11526; a322 = -0.6222; a333 = -7.93831;
            A(1,1,3) = a113; A(1,3,1) = a113;
            A(2,2,3) = a223; A(2,3,2) = a223;
            A(3,1,1) = a311; A(3,2,2) = a322; A(3,3,3) = a333;

        case 'libib2o5'  % LiBiB2O5
            % a123=2.35682, a112=0.34929, a211=0.16101, a222=0.12562,
            % a233=0.1361, a213=-0.05587, a323=6.91074, a312=2.57812
            a123 =  2.35682; a112 =  0.34929; a211 =  0.16101;
            a222 =  0.12562; a233 =  0.1361;  a213 = -0.05587;
            a323 =  6.91074; a312 =  2.57812;
            A(1,2,3) = a123; A(1,3,2) = a123;
            A(1,1,2) = a112; A(1,2,1) = a112;
            A(2,1,1) = a211;
            A(2,2,2) = a222;
            A(2,3,3) = a233;          % a233 = a233 (j=k)
            A(2,1,3) = a213; A(2,3,1) = a213;
            A(3,2,3) = a323; A(3,3,2) = a323;   % a323: (i=3,j=2,k=3), swap j,k -> (3,3,2)
            A(3,1,2) = a312; A(3,2,1) = a312;

        case 'kbi2f7'  % KBi2F7
            % a111=12.64393, a122=1.08802, a133=4.14350, a123=1.59052,
            % a113=1.96801, a112=0.22465, a211=2.59187, a222=0.08263,
            % a233=0.81041, a223=0.51165, a213=0.71432, a212=0.10570,
            % a311=1.51254, a322=0.68235, a333=-0.23019, a323=0.19013,
            % a313=0.39030, a312=0.08381
            A(1,1,1) = 12.64393;
            A(1,2,2) = 1.08802;
            A(1,3,3) = 4.14350;
            A(1,2,3) = 1.59052; A(1,3,2) = 1.59052;
            A(1,1,3) = 1.96801; A(1,3,1) = 1.96801;
            A(1,1,2) = 0.22465; A(1,2,1) = 0.22465;
            A(2,1,1) = 2.59187;
            A(2,2,2) = 0.08263;
            A(2,3,3) = 0.81041;
            A(2,2,3) = 0.51165; A(2,3,2) = 0.51165;
            A(2,1,3) = 0.71432; A(2,3,1) = 0.71432;
            A(2,1,2) = 0.10570; A(2,2,1) = 0.10570;
            A(3,1,1) = 1.51254;
            A(3,2,2) = 0.68235;
            A(3,3,3) = -0.23019;
            A(3,2,3) = 0.19013; A(3,3,2) = 0.19013;
            A(3,1,3) = 0.39030; A(3,3,1) = 0.39030;
            A(3,1,2) = 0.08381; A(3,2,1) = 0.08381;

        case 'banio3'  % crystal system 6
            A(1,1,3) = 0.038385; A(1,3,1) = 0.038385;
            A(2,2,3) = 0.038385; A(2,3,2) = 0.038385;
            A(3,1,1) = 6.89822; A(3,2,2) = 6.89822;
            A(3,3,3) = 27.4628;

        otherwise
            error('Unknown material: %s', material);
    end
end